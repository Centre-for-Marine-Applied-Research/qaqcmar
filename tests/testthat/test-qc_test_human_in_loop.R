hil_t0 <- as.POSIXct("2023-06-01", tz = "UTC")

# Generated by Claude Opus 5.5 with human oversight ----------------------

# one sensor, two variables, four hours
hil_small <- data.frame(
  station = "A",
  deployment_range = "2023-Jun-01 to 2023-Jun-30",
  sensor_type = "aquameasure",
  sensor_serial_number = 1,
  timestamp_utc = hil_t0 + 0:3 * 3600,
  dissolved_oxygen_percent_saturation = c(100, 101, 102, 103),
  temperature_degree_c = c(10, 11, 12, 13),
  grossrange_flag_dissolved_oxygen_percent_saturation = ordered(
    1,
    levels = 1:4
  ),
  grossrange_flag_temperature_degree_c = ordered(c(1, 3, 1, 1), levels = 1:4)
)

# flag temperature 4 for the whole deployment
hil_row <- data.frame(
  station = "A",
  deployment_range = "2023-Jun-01 to 2023-Jun-30",
  variable = "temperature_degree_c",
  sensor_serial_number = NA,
  timestamp_utc_min = NA,
  timestamp_utc_max = NA,
  qc_test = NA,
  qc_flag_value = NA,
  human_in_loop_flag_value = 4,
  hil_comment = "test comment"
)

test_that("qc_test_human_in_loop() returns dat unchanged with no table rows for its deployment", {
  expect_message(
    out <- qc_test_human_in_loop(hil_small, NULL),
    "No flags applied"
  )
  expect_identical(out, hil_small)

  expect_message(
    out <- qc_test_human_in_loop(hil_small, mutate(hil_row, station = "B")),
    "no human in the loop flags"
  )
  expect_identical(out, hil_small)
})

test_that("qc_test_human_in_loop() uses qc_flag_value from the wide flag columns", {
  out <- qc_test_human_in_loop(
    hil_small,
    mutate(hil_row, qc_test = "grossrange", qc_flag_value = 3)
  )

  # only 01:00 has grossrange flag 3
  expect_equal(
    as.numeric(out$human_in_loop_flag_temperature_degree_c),
    c(1, 4, 1, 1)
  )
  expect_equal(
    as.numeric(out$human_in_loop_flag_dissolved_oxygen_percent_saturation),
    c(1, 1, 1, 1)
  )
  expect_equal(out$hil_comment, c(NA, "test comment", NA, NA))
})

test_that("qc_test_human_in_loop() stops for bad dat or human_in_loop_table", {
  expect_error(
    qc_test_human_in_loop(
      mutate(hil_small, station = c("A", "A", "B", "B")),
      hil_row
    ),
    "more than one deployment"
  )
  expect_error(
    qc_test_human_in_loop(qc_test_human_in_loop(hil_small, hil_row), hil_row),
    "already has human in the loop flags"
  )
  expect_error(
    qc_test_human_in_loop(hil_small, select(hil_row, -hil_comment)),
    "missing column"
  )
  expect_error(
    qc_test_human_in_loop(
      hil_small,
      mutate(hil_row, human_in_loop_flag_value = 5)
    ),
    "must be 1, 2, 3 or 4"
  )
  expect_error(
    qc_test_human_in_loop(
      hil_small,
      mutate(
        hil_row,
        timestamp_utc_min = hil_t0 + 3600,
        timestamp_utc_max = hil_t0
      )
    ),
    "is after"
  )
  expect_error(
    qc_test_human_in_loop(hil_small, mutate(hil_row, qc_flag_value = 3)),
    "without << qc_test >>"
  )
  expect_error(
    qc_test_human_in_loop(
      hil_small,
      mutate(hil_row, qc_test = "spike", qc_flag_value = 3)
    ),
    "no flags for << qc_test >>: spike"
  )
})
