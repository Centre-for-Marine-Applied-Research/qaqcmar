  station = "lighthouse",
  deployment_range = "2023-Jan-01 to 2023-Jan-15",
  variable = "dissolved_oxygen_percent_saturation",
  sensor_serial_number = 123,
  timestamp_utc_min = as_datetime("2023-01-22 00:00:00"),
